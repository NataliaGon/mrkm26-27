import os
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat
from cryptography.exceptions import InvalidTag, InvalidSignature

def test_encryption():
    print("--- 3.1 Симетричне автентифіковане шифрування ---")
    message = b"Secret data for scenario"
    aad = b"metadata: user=123"

    # Генеруємо ключ та nonce
    key = ChaCha20Poly1305.generate_key()
    chacha = ChaCha20Poly1305(key)
    nonce = os.urandom(12)

    # Шифруємо
    encrypted = chacha.encrypt(nonce, message, aad)

    # Виводимо всі деталі для звіту
    print("Алгоритм: ChaCha20-Poly1305")
    print(f"Початкове повідомлення: {message.decode()}")
    print(f"Ключ: {len(key) * 8} біт (секретне значення не виводиться)")
    print(f"Nonce (12 байт): {nonce.hex()}")
    print(f"AAD: {aad.decode()}")
    # У ChaCha20 останні 16 байт шифротексту - це тег автентифікації
    print(f"Шифротекст (без тегу): {encrypted[:-16].hex()}")
    print(f"Authentication Tag (16 байт): {encrypted[-16:].hex()}")

    # Розшифровуємо
    decrypted = chacha.decrypt(nonce, encrypted, aad)
    print(f"Розшифроване повідомлення: {decrypted.decode()}")
    print("Статус: УСПІШНО\n")

    # Симулюємо пошкодження даних
    modified = bytearray(encrypted)
    modified[5] ^= 0xFF

    try:
        chacha.decrypt(nonce, bytes(modified), aad)
    except InvalidTag:
        print("Спроба розшифрувати підроблений шифротекст: InvalidTag")
        print("Статус: Змінений шифротекст успішно відхилено\n")

def test_signature():
    print("--- 3.2 Цифровий підпис ---")
    message = b"Document to sign: Contract #45"

    # Генеруємо ключі
    private_key = ec.generate_private_key(ec.SECP256R1())
    public_key = private_key.public_key()

    # Створюємо підпис
    signature = private_key.sign(message, ec.ECDSA(hashes.SHA256()))

    # Виводимо деталі
    print("Алгоритм: ECDSA (SECP256R1)")
    print(f"Початкове повідомлення: {message.decode()}")
    public_bytes = public_key.public_bytes(Encoding.X962, PublicFormat.CompressedPoint)
    print(f"Відкритий ключ (hex): {public_bytes.hex()}")
    print(f"Підпис (hex): {signature.hex()[:64]}...")

    # Перевіряємо оригінал
    public_key.verify(signature, message, ec.ECDSA(hashes.SHA256()))
    print("Перевірка підпису оригінального повідомлення: УСПІШНО\n")

    # Симулюємо підміну документа
    modified_message = b"Document to sign: Contract #99"
    print(f"Змінене повідомлення: {modified_message.decode()}")

    try:
        public_key.verify(signature, modified_message, ec.ECDSA(hashes.SHA256()))
    except InvalidSignature:
        print("Перевірка підпису зміненого повідомлення: InvalidSignature")
        print("Статус: Підроблений документ успішно відхилено\n")

if __name__ == "__main__":
    test_encryption()
    test_signature()